// ============================================================================
// Таблицы на телефоне.
//
// Таблица на 5-6 колонок в экран шириной 390 не влезает никак. Она либо уезжает
// вбок, и последних колонок просто не видно, либо шапка ломается по слогам
// и превращается в столбик из отдельных слов. И то и другое человек читает
// одинаково: «непонятные цифры».
//
// Поэтому на узком экране таблица перестаёт быть таблицей и становится списком
// карточек: одна строка — одна карточка, и в каждой строке карточки написано,
// что это за число. Названия берутся из шапки самой таблицы, так что подписи
// не нужно дублировать в разметке и они не могут разойтись с колонками.
//
// Здесь только простановка подписей; всё остальное делает CSS по @media.
// ============================================================================

/**
 * Ставит подписи один раз и дальше следит сам.
 *
 * Панели перерисовываются по-разному: часть на каждом ходу, часть только при
 * переключении вкладки справа. Вызывать простановку из каждого места — значит
 * однажды забыть одно, и в нём числа молча останутся без имён. Наблюдатель
 * ловит любую замену разметки, откуда бы она ни пришла.
 *
 * Смотрим только за появлением узлов: сами подписи ставятся атрибутами,
 * а изменения атрибутов наблюдатель не слушает — зацикливания не будет.
 */
export function watchTables(root = document.body) {
  labelTables(root);
  if (typeof MutationObserver !== 'function') return;
  let queued = false;
  const observer = new MutationObserver(() => {
    if (queued) return;
    queued = true;
    // Ждём конца текущей перерисовки: панелей много, и метить каждую
    // по отдельности означало бы пройти по всем таблицам десяток раз.
    setTimeout(() => { queued = false; labelTables(root); }, 0);
  });
  observer.observe(root, { childList: true, subtree: true });
}

/**
 * Проставляет каждой ячейке имя её колонки в data-label.
 * Вызывается после каждой перерисовки: таблицы собираются заново, и вместе
 * с ними пропадают все атрибуты.
 *
 * @param {ParentNode} root где искать таблицы
 */
export function labelTables(root = document) {
  for (const table of root.querySelectorAll('table.data')) {
    const heads = [...table.querySelectorAll('thead th')].map((h) => h.textContent.trim());
    if (!heads.length) continue;
    for (const row of table.querySelectorAll('tbody tr')) {
      let col = 0;
      for (const cell of row.children) {
        // colspan сдвигает нумерацию: без этого подписи расползутся
        // на строках-подытогах, где одна ячейка занимает половину таблицы.
        const label = heads[col] ?? '';
        if (label) cell.setAttribute('data-label', label);
        else cell.removeAttribute('data-label');
        col += cell.colSpan || 1;
      }
    }
  }
}
