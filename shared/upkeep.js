// Стоимость того, что уже построено.
//
// Во всех трёх играх есть рычаг «вложиться в технологии». Долгое время он был
// устроен нечестно: вложение разово списывалось, накопленный уровень оставался
// навсегда и не стоил ничего. Так не бывает.
//
// Здесь две статьи, которых в модели не хватало.
//
// 1. СОДЕРЖАНИЕ. Каждая построенная функция требует, чтобы её поддерживали:
//    обновляли библиотеки, чинили после чужих изменений, объясняли новым
//    людям. Счёт приходит каждый месяц и не зависит от того, пользуются ли
//    функцией. Поэтому «вложить разом полмиллиарда» — это не разовая трата,
//    а постоянное обязательство, и решение о вложении надо принимать не по
//    цене, а по цене вместе с содержанием.
//
// 2. ИНФРАСТРУКТУРА. Серверы растут не от вашего решения, а от нагрузки:
//    от заказов, часов просмотра, проданных билетов. Это единственная статья,
//    которая дорожает ровно тогда, когда дела идут хорошо. Технологии её
//    удешевляют — в этом и есть их окупаемость, помимо качества продукта.
// ============================================================================

/**
 * Ежемесячное (в доставке — еженедельное) содержание накопленного продукта.
 * Считается от суммы вложений, а не от уровня: уровень насыщается, а счёт за
 * поддержку — нет. Именно поэтому чрезмерные ранние вложения давят потом.
 */
export function platformUpkeep(stock, rate) {
  return Math.max(0, stock) * rate;
}

/**
 * Инфраструктура под нагрузкой. Технологический уровень её удешевляет,
 * но не отменяет: чем больше вы продаёте, тем больше платите.
 *
 * @param load      единицы нагрузки (заказы, часы, билеты)
 * @param perUnit   базовая стоимость единицы
 * @param techLevel 0..1 — уровень технологий
 * @param relief    какую долю стоимости снимает полный технологический уровень
 */
export function infraCost(load, perUnit, techLevel = 0, relief = 0.35) {
  const discount = 1 - relief * Math.min(1, Math.max(0, techLevel));
  return Math.max(0, load) * perUnit * discount;
}
