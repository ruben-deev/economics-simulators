// ============================================================================
// Кнопка «наверх».
//
// Экран хода на телефоне — это несколько экранов прокрутки: итоги месяца,
// рынок вокруг, релизы, потом вся левая колонка с рычагами. Показатели
// компании (деньги, подписчики, месяц) живут в шапке, а шапка на телефоне
// НЕ липкая: она занимает пол-экрана, держать её сверху нельзя. Значит,
// свериться с деньгами посреди решения можно было только долгой прокруткой
// большим пальцем. На десктопе шапка липкая, и там кнопка нужна меньше —
// но и мешает она там нулю: это ещё одна кнопка в ряду служебных.
//
// Кнопка живёт В ПОЛОСЕ КНОПОК, а не висит поверх страницы. Плавающий
// кружок в углу пробовался первым и на телефоне ложился прямо на варианты
// рычага («Предложить второй дом»): полоса кнопок на телефоне закреплена
// внизу, места в ней хватает, и там кнопка не перекрывает ничего.
// Скрывать её на верху страницы тоже не стали: соседние кнопки при
// прокрутке разъезжались бы вбок, а «Заново» рядом с «наверх» — не та
// пара, где стоит двигать цели под пальцем.
// ============================================================================
import { getLang } from './i18n.js';

const LABEL = { ru: 'Наверх, к показателям', en: 'Back to top' };

let up = null;

/** Переименовать после смены языка. Без кнопки — ничего не делает. */
export function relabelScrollTop() {
  if (up) up.title = up.ariaLabel = LABEL[getLang()] ?? LABEL.ru;
}

export function mountScrollTop() {
  up = document.getElementById('btn-up');
  if (!up) return;
  relabelScrollTop();
  up.addEventListener('click', () => {
    scrollTo({ top: 0, behavior: 'smooth' });
    // Возврат фокуса в начало страницы: иначе клавиатура и скринридер
    // остаются там, откуда прокрутили, и Tab продолжает с середины.
    const first = document.querySelector('header a:not([hidden]), header button:not([hidden])');
    if (first) first.focus({ preventScroll: true });
  });
}
