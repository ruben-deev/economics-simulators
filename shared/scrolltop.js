// ============================================================================
// Кнопка «наверх».
//
// Экран хода на телефоне — это несколько экранов прокрутки: итоги месяца,
// рынок вокруг, релизы, потом вся левая колонка с рычагами. Показатели
// компании (деньги, подписчики, месяц) живут в шапке, а шапка на телефоне
// НЕ липкая: она занимает пол-экрана, держать её сверху нельзя.
//
// Где кнопка стоит и почему именно там — история из трёх попыток:
//   1. Плавающий кружок 44 px в углу — ложился на варианты рычага.
//   2. Кнопка в полосе рядом с «Заново» — соседство скверное (промах по
//      «Заново» стоит партии), место нестандартное, а сама стрелка узкая.
//   3. Плавающая круглая кнопка 56 px, как её ждут на телефоне: правый
//      нижний угол над закреплённой полосой, появляется только после
//      прокрутки на экран и исчезает наверху. Перекрытие содержимого у
//      такой кнопки есть всегда — зато она видна ровно тогда, когда нужна,
//      и не соседствует ни с чем разрушительным.
// ============================================================================
import { getLang } from './i18n.js';

const LABEL = { ru: 'Наверх, к показателям', en: 'Back to top' };

let up = null;

/** Переименовать после смены языка. Без кнопки — ничего не делает. */
export function relabelScrollTop() {
  if (up) up.title = up.ariaLabel = LABEL[getLang()] ?? LABEL.ru;
}

export function mountScrollTop() {
  if (up) return;
  up = document.createElement('button');
  up.id = 'btn-up';
  up.className = 'btn-up';
  up.type = 'button';
  up.hidden = true;
  up.textContent = '↑';
  relabelScrollTop();
  document.body.appendChild(up);

  // Порог — экран прокрутки: выше кнопка не нужна, а место она занимает.
  const toggle = () => { up.hidden = scrollY < innerHeight * 0.75; };
  toggle();
  addEventListener('scroll', toggle, { passive: true });
  addEventListener('resize', toggle);
  up.addEventListener('click', () => {
    scrollTo({ top: 0, behavior: 'smooth' });
    // Возврат фокуса в начало страницы: иначе клавиатура и скринридер
    // остаются там, откуда прокрутили, и Tab продолжает с середины.
    const first = document.querySelector('header a:not([hidden]), header button:not([hidden])');
    if (first) first.focus({ preventScroll: true });
  });
}
