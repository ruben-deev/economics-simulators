// ============================================================================
// Как считается оценка компании — общая часть для всех трёх игр.
//
// Раньше каждая игра брала выручку и маржу из последнего хода. Это открывало
// стратегию, не имеющую отношения к экономике: задрать все ставки, обнулить
// все вложения — и сделать это за ход до конца партии. Бизнес разваливался,
// а итоговый счёт рос. Измерено: в кинотеатре такой рывок давал +92%,
// в билетном сервисе +58%.
//
// Лечится не запретом, а окном: инвестор смотрит не на последний месяц, а на
// то, как компания шла последние полгода. Рывок в один ход в такое окно почти
// не попадает, а рывок на полгода — это уже не рывок, а стратегия, и она
// честно проигрывает по росту.
//
// Второе правило здесь же: сжатие должно стоить денег. Если множитель за
// падение выручки не наказывает, «снять сливки и растерять базу» ничего
// не стоит и снова становится выигрышной стратегией.
// ============================================================================

/**
 * Среднее значение за последние n ходов.
 *
 * Последний ход весит столько же, сколько любой другой в окне, — поэтому
 * его нельзя купить одним решением.
 *
 * @param history массив отчётов (как в state.history)
 * @param n       длина окна в ходах
 * @param pick    что берём из отчёта
 */
export function windowAvg(history, n, pick) {
  const window = history.slice(-Math.max(1, n));
  if (!window.length) return 0;
  return window.reduce((sum, r) => sum + (pick(r) ?? 0), 0) / window.length;
}

/**
 * Темп роста: сумма за последние n ходов против суммы за предыдущие n.
 * Возвращает прирост (0.2 = плюс двадцать процентов), а не отношение.
 *
 * Пока истории на два окна не хватает, роста ещё не видно — возвращается
 * fallback, а не выдуманное число.
 */
export function windowGrowth(history, n, pick, fallback = 0.25) {
  const size = Math.max(1, n);
  const recent = history.slice(-size).reduce((s, r) => s + (pick(r) ?? 0), 0);
  const older = history.slice(-2 * size, -size).reduce((s, r) => s + (pick(r) ?? 0), 0);
  if (older <= 0) return recent > 0 ? fallback : 0;
  return recent / older - 1;
}

/**
 * Множитель к выручке.
 *
 * @param growth       прирост за окно (может быть отрицательным)
 * @param margin       маржа за то же окно
 * @param k            коэффициенты игры
 *
 * Ключевое: `growthFloor` строго меньше нуля. Сжимающийся бизнес стоит
 * дешевле стоящего на месте — иначе жадность бесплатна.
 */
export function revenueMultiple(growth, margin, k) {
  const {
    base, growthWeight, marginWeight, marginPenalty,
    growthFloor = -0.5, growthCap = 1,
    marginFloor = -0.4, marginCap = 0.25,
    min = 0.5, max = 12,
  } = k;
  const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x));
  const growthScore = clamp(growth, growthFloor, growthCap);
  const marginScore = clamp(margin, marginFloor, marginCap) / marginCap;
  return clamp(
    base + growthWeight * growthScore
      + marginWeight * Math.max(0, marginScore) + marginPenalty * Math.min(0, marginScore),
    min, max,
  );
}

/**
 * Условия раунда: сколько доли уходит за деньги.
 *
 * Две защиты, без которых один раунд решает всю партию.
 *
 * ПОЛ ПОД ОЦЕНКОЙ. На третьей неделе компания по формуле стоит копейки, и
 * раунд в её половину капитала забирает почти всё. В жизни так не бывает:
 * посевной раунд оценивают по рынку и команде, а не по выручке, которой
 * ещё нет.
 *
 * ПОТОЛОК НА ДОЛЮ. Никто не продаёт три четверти компании за один раунд —
 * инвестор первым и откажется: основатель без доли перестаёт работать.
 *
 * Без этих двух строк вложить лишний миллион в маркетинг означало не
 * «выросли заказы», а «раунд случился на шесть недель раньше и стоил
 * шестьдесят пунктов доли». Измерено: та же компания с той же оценкой
 * оставляла основателю 84% или 20% в зависимости от одной недели.
 */
export function roundTerms(valuation, amount, { floor, maxShare = 0.75, minShare = 0.02 }) {
  const pre = Math.max(floor, valuation);
  const raw = amount / (pre + amount);
  const dilution = Math.min(maxShare, Math.max(minShare, raw));
  return { pre, post: pre + amount, amount, dilution };
}
