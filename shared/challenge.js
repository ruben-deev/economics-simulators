// ============================================================================
// Челлендж недели и код партии из ссылки.
//
// Идея: один город на всех. Код недели детерминирован от даты (ISO-неделя),
// поэтому витрина, игры и любые посты называют один и тот же код без
// сервера и синхронизации. Ссылка вида …/games/foodtech/?code=2026-w35
// приносит код с собой: экран приветствия подставляет его в поле сам.
//
// Код намеренно нейтрален к языку — он попадает в сид мира и в мировую
// таблицу, где русская и английская версии живут в одной шкале.
// ============================================================================

/** ISO-номер недели: понедельник — первый день, первая неделя — с четвергом. */
export function challengeCode(now = new Date()) {
  const d = new Date(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()));
  const day = d.getUTCDay() || 7;
  d.setUTCDate(d.getUTCDate() + 4 - day);
  const year = d.getUTCFullYear();
  const start = Date.UTC(year, 0, 1);
  const week = Math.ceil(((d.getTime() - start) / 86400000 + 1) / 7);
  return `${year}-w${String(week).padStart(2, '0')}`;
}

// Код партии — это буквы, цифры, пробел и дефис: «урок-7б», «2026-w35».
// Всё остальное вырезается. Причина не косметическая: код приходит из
// ?code= в ссылке, попадает в сид мира, а оттуда — в справку («ваш код
// партии») и в таблицу рекордов, где подставляется в разметку. Замер:
// ссылка с ?code=<img src=x onerror=…> выполняла скрипт при открытии
// справки. Чистим на входе, чтобы не гоняться за каждым местом вывода.
export function safeGameCode(raw) {
  return String(raw ?? '').replace(/[^\p{L}\p{N} _-]+/gu, '').trim().slice(0, 64);
}

/** Код партии из ссылки (?code=…) — пустая строка, если его нет. */
export function urlGameCode() {
  try {
    return safeGameCode(new URLSearchParams(window.location.search).get('code') || '');
  } catch {
    return '';
  }
}

// --- Город недели по умолчанию -------------------------------------------
// Новая партия (чистое устройство или «заново») сама предлагает код недели,
// пока он на этом устройстве ещё не игрался в этой игре. Отметка ставится
// при старте партии на коде недели; на следующей неделе код другой — и
// приглашение возвращается само. Игрок всегда может стереть код и получить
// случайный город: это приглашение, а не принуждение.

const playedKey = (game, code) => `weekly-played-${game}-${code}`;

/** Код недели, если он ещё не игрался в этой игре на этом устройстве. */
export function weeklySeedToPlay(game) {
  const code = challengeCode();
  try {
    return localStorage.getItem(playedKey(game, code)) ? '' : code;
  } catch {
    // Приватный режим: не навязываем неделю снова и снова
    return '';
  }
}

/** Отметить: на этом устройстве неделя в этой игре сыграна. */
export function markWeeklyPlayed(game, seed) {
  if (!seed || seed !== challengeCode()) return;
  try { localStorage.setItem(playedKey(game, seed), '1'); } catch { /* не критично */ }
}
