// ============================================================================
// Погода — постоянно действующий фактор, а не редкое событие.
//
// Каждая неделя имеет свой тип погоды, разыгрываемый по сезонной таблице.
// Погода бьёт с двух сторон одновременно: поднимает спрос (никто не хочет
// выходить из дома) и режет пропускную способность (курьеры едут медленнее).
// Именно это сочетание ломает сроки доставки в реальных сервисах.
//
// Прогноз на следующую неделю публичен — метеосводка доступна всем. Ценность
// не в информации, а в реакции: успеть нанять курьеров и поднять надбавку.
// ============================================================================

import { weightedPick } from '../../../../shared/rng.js';

// severity — насколько погода «плохая» (0 = ясно, 1 = максимум).
// От неё зависит и размер надбавки курьеру, и то, как сильно она помогает.
// Мощность в тяжёлую погоду режется всерьёз: без надбавки заметная часть
// курьеров просто не выходит на смену. Прежние значения (шторм ×0.80) делали
// плохую погоду шумом: потерянное восстанавливалось за неделю, и готовиться
// к шторму было незачем — что и показал замер.
export const WEATHER = {
  clear:  { id: 'clear',  icon: '☀️', demand: 1.00, capacity: 1.00, churn: 0,    severity: 0 },
  rain:   { id: 'rain',   icon: '🌧️', demand: 1.16, capacity: 0.88, churn: 0.05, severity: 0.45 },
  storm:  { id: 'storm',  icon: '⛈️', demand: 1.30, capacity: 0.60, churn: 0.17, severity: 1.00 },
  heat:   { id: 'heat',   icon: '🔥', demand: 1.04, capacity: 0.76, churn: 0.12, severity: 0.70 },
  snow:   { id: 'snow',   icon: '🌨️', demand: 1.22, capacity: 0.66, churn: 0.13, severity: 0.80 },
  ice:    { id: 'ice',    icon: '🧊', demand: 1.10, capacity: 0.56, churn: 0.21, severity: 1.00 },
  frost:  { id: 'frost',  icon: '❄️', demand: 1.14, capacity: 0.78, churn: 0.09, severity: 0.60 },
};

// Неделя 1 — начало января, дальше по календарю
export function seasonOf(week) {
  const w = ((Math.max(1, week) - 1) % 52) + 1;
  if (w <= 8 || w >= 49) return 'winter';
  if (w <= 21) return 'spring';
  if (w <= 34) return 'summer';
  return 'autumn';
}

// Сезонные вероятности. Гололёд бывает только зимой, жара — только летом.
const SEASON_WEIGHTS = {
  winter: { clear: 30, snow: 28, frost: 24, ice: 12, storm: 6 },
  spring: { clear: 45, rain: 35, storm: 10, frost: 10 },
  summer: { clear: 45, rain: 25, storm: 12, heat: 18 },
  autumn: { clear: 35, rain: 38, storm: 15, frost: 12 },
};

export function rollWeather(rng, week) {
  const table = SEASON_WEIGHTS[seasonOf(week)];
  const picked = weightedPick(rng, Object.entries(table).map(([id, weight]) => ({ id, weight })));
  return picked ? picked.id : 'clear';
}

/**
 * Итоговые множители недели с учётом надбавки курьерам за плохую погоду.
 *
 * Два правила, из-за которых надбавка — решение, а не настройка.
 *
 * ОБЕЩАНИЕ ПЛАТНОЕ. Раньше надбавка была условной: в ясную погоду она не
 * стоила ничего, и «выставил 80 ₽ и забыл» было бесплатно в хорошие недели
 * и автоматически правильно в плохие. Замер показал, что реагировать на
 * прогноз и играть наоборот было одинаково (−2.6% и −2.5%): механика играла
 * сама за себя. Теперь у гарантии есть безусловная часть — курьер, которому
 * обещали доплату за погоду, получает её базу и в ясную неделю: гарантия
 * входит в его ожидаемый заработок, иначе это не гарантия.
 *
 * ПРИВЫКАНИЕ. Надбавка, которая горит всегда, перестаёт быть стимулом:
 * через пару месяцев курьеры считают её частью ставки, и в настоящий шторм
 * она уже никого дополнительно не выводит. Свежесть надбавки — habit —
 * копится, пока надбавка включена, и рассеивается, пока выключена.
 * Включать её по прогнозу — и дешевле, и действеннее.
 *
 * @param habit 0..1 — насколько курьеры привыкли к надбавке (state.bonusHabit)
 */
export function weatherEffect(type, weatherBonus = 0, habit = 0) {
  const w = WEATHER[type] ?? WEATHER.clear;
  // Полное покрытие — 80 ₽ надбавки в самую скверную погоду...
  const rawCoverage = Math.min(1, Math.max(0, weatherBonus) / 80);
  // ...но привычная надбавка мотивирует хуже свежей
  const coverage = rawCoverage * (1 - 0.80 * Math.min(1, Math.max(0, habit)));

  return {
    ...w,
    // Безусловная часть (35%) платится в любую погоду, остальное — по тяжести
    payPerOrder: weatherBonus * 0.4 * (0.35 + 0.65 * w.severity),
    // Деньги возвращают до 80% потерянной пропускной способности:
    // курьеры выходят на смену, но физику дороги надбавкой не отменишь
    capacityMult: w.capacity + (1 - w.capacity) * 0.80 * coverage,
    churnAdd: w.churn * (1 - 0.85 * coverage),
    demandMult: w.demand,
  };
}

/**
 * Недельный шаг привыкания: надбавка включена — привычка копится,
 * выключена — рассеивается. Восемь-десять недель непрерывной надбавки —
 * и она уже «часть зарплаты».
 */
export function bonusHabitStep(habit, weatherBonus) {
  const h = Math.min(1, Math.max(0, habit ?? 0));
  const on = weatherBonus > 0 ? 1 : 0;
  return h + (on - h) * 0.12;
}
